/**
 * Feature extraction for the Publish score model — the TypeScript mirror of
 * `ml/publishml/features.py`.
 *
 * THIS FILE AND THE PYTHON ONE MUST AGREE EXACTLY.
 * The model is a positional vector of 64 numbers. If this extractor computes
 * `title_len` differently from the one that produced the training data, every
 * score is wrong in a way that no test of *this* file alone would catch. So:
 *
 *   - the column order comes from the model artefact, never from this file
 *   - `src/lib/ml/features.test.ts` runs both extractors over shared fixtures
 *     exported by `python -m publishml.export` and asserts equality
 *   - the awkward-looking helpers below (`codePoints`, `splitLines`) exist
 *     precisely because the obvious JavaScript is *not* what Python does
 *
 * The three places JavaScript silently disagrees with Python, all handled:
 *   1. `len(s)` counts code points; `s.length` counts UTF-16 units. An emoji is
 *      1 in Python and 2 in JS. → `codePoints()`.
 *   2. `str.splitlines()` returns `[]` for the empty string and drops a trailing
 *      terminator; `split('\n')` returns `['']` and keeps it. → `splitLines()`.
 *   3. `datetime.weekday()` is Monday=0; `Date.getUTCDay()` is Sunday=0.
 *
 * Thumbnail features are NOT computed here. They need pixel access and are
 * produced by `ml/publishml/thumbs.py`; the caller passes them in when it has
 * them. When it does not, they are left absent and `has_thumb` is 0 — the same
 * thing the trainer saw for videos whose thumbnail never downloaded, so the model
 * already knows how to treat that row.
 */

